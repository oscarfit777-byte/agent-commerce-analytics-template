-- Únicamente 4 tablas canónicas: profiles, orders, plans, leads
-- =====================================================================

-- 1. TABLA: profiles (vinculada a auth.users con roles en MAYÚSCULAS)
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  email text not null,
  full_name text,
  phone text,
  role text default 'ALUMNO' check (role in ('ADMIN', 'COACH', 'ALUMNO', 'LEAD')),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. TABLA: plans (Única fuente de verdad de precios y servicios)
create table if not exists public.plans (
  id text primary key,
  title text not null,
  price_usd numeric(10,2) not null,
  billing_type text not null,
  badge text,
  description text,
  active boolean default true,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

