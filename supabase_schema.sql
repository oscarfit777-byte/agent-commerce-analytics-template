-- 3. TABLA: orders (Registro de pedidos comerciales con estado inicial pendiente_verificacion)
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_code text not null unique,
  product_id text references public.plans(id) on delete set null,
  product_name text not null,
  amount_usd numeric(10,2) not null,
  billing_type text not null,
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  payment_method text default 'transferencia_bancaria',
  status text default 'pendiente_verificacion' check (status in ('pendiente_verificacion', 'verificado_activo', 'cancelado')),
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 4. TABLA: leads (Prospectos captados por el Agente de IA Comercial y la Web)
create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  full_name text not null,
  email text,
  phone text,
  interest_plan text,
  goal text,
  source text default 'chat_ia',
  status text default 'nuevo' check (status in ('nuevo', 'contactado', 'convertido', 'descartado')),
  notes text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- =====================================================================
-- HABILITACIÓN DE SEGURIDAD RLS (Row Level Security)
-- =====================================================================
alter table public.profiles enable row level security;
alter table public.plans enable row level security;
alter table public.orders enable row level security;
alter table public.leads enable row level security;

-- Políticas para profiles:
create policy "Usuarios pueden ver su propio perfil" 
on public.profiles for select 
using (auth.uid() = id);

create policy "Admins y Coaches pueden ver todos los perfiles" 
on public.profiles for select 
using (
  exists (
    select 1 from public.profiles 
    where profiles.id = auth.uid() 
    and profiles.role in ('ADMIN', 'COACH')
  )
);

create policy "Permitir insercion automatica de perfil" 
on public.profiles for insert 
with check (true);

create policy "Permitir actualizacion para Admins y Coaches" 
on public.profiles for update 
using (
  auth.uid() = id or 
  exists (
    select 1 from public.profiles 
    where profiles.id = auth.uid() 
    and profiles.role in ('ADMIN', 'COACH')
  )
);

-- Políticas para plans:
create policy "Lectura pública de planes" 
on public.plans for select 
using (true);

-- Políticas para orders:
create policy "Inserción pública de pedidos" 
on public.orders for insert 
with check (true);

create policy "Lectura de pedidos para Admins y Coaches" 
on public.orders for select 
using (true);

create policy "Actualización de pedidos para Admins y Coaches" 
on public.orders for update 
using (true);

-- Políticas para leads:
create policy "Inserción pública de prospectos desde el Chat IA o Web" 
on public.leads for insert 
with check (true);

create policy "Lectura y gestión de leads para Admins y Coaches" 
on public.leads for select 
using (true);

create policy "Actualización de leads para Admins y Coaches" 
on public.leads for update 
using (true);
